"""Country outlines for the Thailand video's cartoon characters, as SVG paths in a 1000-unit box.

    python3 -I tools/thailand_char_shapes.py      # reads src/thailand/geo.json, writes src/thailand/motion/shapes.ts

Local equirectangular projection (x scaled by cos of the shape's mid latitude), fitted to 1000 units on the long side,
simplified to keep the files small. Natural Earth (public domain).
"""
import json
import math
from pathlib import Path

from shapely.geometry import Polygon

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    g = json.loads((ROOT / "src" / "thailand" / "geo.json").read_text())
    out = ["// Generated by tools/thailand_char_shapes.py from Natural Earth outlines (public domain). Do not edit by hand.",
           "// Each shape is an SVG path in its own box (w × h, long side 1000), y down.", "",
           "export type CountryShape = { d: string; w: number; h: number };", ""]
    for name, pts in g["char"].items():
        lat0 = sum(p[1] for p in pts) / len(pts)
        k = math.cos(math.radians(lat0))
        xy = [(x * k, -y) for x, y in pts]
        poly = Polygon(xy).simplify(0.035, preserve_topology=True)
        c = list(poly.exterior.coords)
        x0, y0 = min(p[0] for p in c), min(p[1] for p in c)
        x1, y1 = max(p[0] for p in c), max(p[1] for p in c)
        s = 1000 / max(x1 - x0, y1 - y0)
        d = "M" + "L".join(f"{(x - x0) * s:.0f},{(y - y0) * s:.0f}" for x, y in c) + "Z"
        out.append(f"export const {name.upper()}: CountryShape = {{ w: {round((x1 - x0) * s)}, h: {round((y1 - y0) * s)}, d: '{d}' }};")
        print(name, len(c), "points")
    (ROOT / "src" / "thailand" / "motion" / "shapes.ts").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
